#!/usr/bin/env python3
#
# Regenerates the grapheme cluster segmentation tables used by mosaic-runtime
# (Grapheme_Cluster_Break and Extended_Pictographic properties), writing
# GraphemeBreakTables.kt.
#
# Run from a scratch directory (with network access) so downloaded Unicode data
# files are cached there instead of in the repository. Supports --check
# (default) and --write, matching scripts/unicode.py.
#
# Sources: auxiliary/GraphemeBreakProperty.txt, emoji/emoji-data.txt (ucd/emoji),
# and DerivedCoreProperties.txt (for Indic_Conjunct_Break).
import os
import re
import sys
import urllib.request

UNICODE_VERSION = "16.0.0"
KOTLIN_TABLES_PATH = os.path.abspath(
    os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "..",
        "mosaic-runtime",
        "src",
        "commonMain",
        "kotlin",
        "com",
        "jakewharton",
        "mosaic",
        "text",
        "grapheme",
        "GraphemeBreakTables.kt",
    )
)
GCB_CLASSES = [
    "CR",
    "LF",
    "Control",
    "Extend",
    "ZWJ",
    "Regional_Indicator",
    "Prepend",
    "SpacingMark",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
]


def fetch_open(filename: str, subdir: str):
    """Opens `filename`, fetching it from unicode.org into the working directory if absent."""
    if not os.path.exists(filename):
        url = f"https://www.unicode.org/Public/{UNICODE_VERSION}/{subdir}/{filename}"
        urllib.request.urlretrieve(url, filename)
    return open(filename, encoding="utf-8")


def load_ranges(filename: str, subdir: str, pattern: str) -> list[list[int]]:
    """Loads property ranges, returning a sorted list of [start, end] inclusive."""
    ranges = []
    single = re.compile(rf"^([0-9A-F]+)\s*;\s*{pattern}\s*#")
    multiple = re.compile(rf"^([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*{pattern}\s*#")
    with fetch_open(filename, subdir) as f:
        for line in f:
            if m := single.match(line):
                cp = int(m.group(1), 16)
                ranges.append([cp, cp])
            elif m := multiple.match(line):
                ranges.append([int(m.group(1), 16), int(m.group(2), 16)])
    ranges.sort()
    return ranges


def merge(ranges: list[list[int]]) -> list[list[int]]:
    merged = []
    for start, end in ranges:
        if merged and start <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], end)
        else:
            merged.append([start, end])
    return merged


def load_gcb_classes() -> list[tuple[int, int, int]]:
    """Returns sorted [start, end, class_id] triples for non-Other GCB classes."""
    triples = []
    for class_id, name in enumerate(GCB_CLASSES, start=1):
        for start, end in load_ranges("GraphemeBreakProperty.txt", "ucd/auxiliary", name):
            triples.append((start, end, class_id))
    triples.sort()
    merged = []
    for start, end, class_id in triples:
        if merged and start <= merged[-1][1] + 1 and merged[-1][2] == class_id:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end), class_id)
        else:
            merged.append((start, end, class_id))
    return merged


def load_extended_pictographic() -> list[tuple[int, int]]:
    return [(s, e) for s, e in merge(load_ranges("emoji-data.txt", "ucd/emoji", "Extended_Pictographic"))]


def load_indic_conjunct() -> list[tuple[int, int, int]]:
    """Returns sorted [start, end, value] ranges for Indic_Conjunct_Break (InCB), where value is
    1 for Consonant, 2 for Linker, and 3 for Extend."""
    values = {"Consonant": 1, "Linker": 2, "Extend": 3}
    triples = []
    single = re.compile(r"^([0-9A-F]+)\s*; InCB; (Consonant|Linker|Extend)\s*#")
    multiple = re.compile(r"^([0-9A-F]+)\.\.([0-9A-F]+)\s*; InCB; (Consonant|Linker|Extend)\s*#")
    with fetch_open("DerivedCoreProperties.txt", "ucd") as f:
        for line in f:
            if m := single.match(line):
                cp = int(m.group(1), 16)
                triples.append((cp, cp, values[m.group(2)]))
            elif m := multiple.match(line):
                triples.append((int(m.group(1), 16), int(m.group(2), 16), values[m.group(3)]))
    triples.sort()
    merged = []
    for start, end, value in triples:
        if merged and start <= merged[-1][1] + 1 and merged[-1][2] == value:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end), value)
        else:
            merged.append((start, end, value))
    return merged


def emit_kotlin(
    gcb: list[tuple[int, int, int]],
    ep: list[tuple[int, int]],
    incb: list[tuple[int, int, int]],
) -> str:
    out = []
    w = out.append
    w("// Grapheme cluster segmentation data (UAX #29).")
    w("//")
    w("// NOTE: generated by scripts/grapheme.py, do not edit directly.")
    w("package com.jakewharton.mosaic.text.grapheme")
    w("")
    w("// Sorted, non-overlapping [start, end, class] ranges of the Grapheme_Cluster_Break")
    w("// property. Class values are the GCB_* constants in GraphemeBreak.kt.")
    w("internal val GCB_RANGES: IntArray = intArrayOf(")
    for i in range(0, len(gcb), 4):
        chunk = gcb[i : i + 4]
        w("    " + " ".join(f"0x{s:X}, 0x{e:X}, {c}," for s, e, c in chunk))
    w(")")
    w("")
    w("// Sorted, non-overlapping [start, end] ranges of the Extended_Pictographic property.")
    w("internal val EXTENDED_PICTOGRAPHIC_RANGES: IntArray = intArrayOf(")
    for i in range(0, len(ep), 6):
        chunk = ep[i : i + 6]
        w("    " + " ".join(f"0x{s:X}, 0x{e:X}," for s, e in chunk))
    w(")")
    w("")
    w("// Sorted, non-overlapping [start, end, value] ranges of the Indic_Conjunct_Break (InCB)")
    w("// property. Values use the INC_* constants in GraphemeBreak.kt.")
    w("internal val INDIC_CONJUNCT_RANGES: IntArray = intArrayOf(")
    for i in range(0, len(incb), 4):
        chunk = incb[i : i + 4]
        w("    " + " ".join(f"0x{s:X}, 0x{e:X}, {v}," for s, e, v in chunk))
    w(")")
    return "\n".join(out) + "\n"


def main() -> int:
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    generated = emit_kotlin(
        load_gcb_classes(), load_extended_pictographic(), load_indic_conjunct()
    )
    try:
        with open(KOTLIN_TABLES_PATH, encoding="utf-8", newline="") as f:
            current = f.read()
    except FileNotFoundError:
        current = ""
    if mode == "--write":
        if current != generated:
            with open(KOTLIN_TABLES_PATH, "w", encoding="utf-8", newline="") as f:
                f.write(generated)
            print(f'Wrote autogenerated tables to "{KOTLIN_TABLES_PATH}"')
        else:
            print(f'Autogenerated tables in "{KOTLIN_TABLES_PATH}" are already up to date.')
        return 0
    if current != generated:
        sys.stderr.write(f'ERROR: "{KOTLIN_TABLES_PATH}" is out of date; run `python3 scripts/grapheme.py --write`.\n')
        return 1
    print(f'Autogenerated tables in "{KOTLIN_TABLES_PATH}" are up to date.')
    return 0


if __name__ == "__main__":
    sys.exit(main())
